export function translateTerm(text, lang) {
  if (lang !== 'he' || typeof text !== 'string') return text;
  return TERMS_HE.get(text) ?? text;
}

export function createTranslator(lang = 'he') {
  const code = lang === 'en' ? 'en' : 'he';
  const dict = STRINGS[code];
  return {
    lang: code,
    dir: code === 'he' ? 'rtl' : 'ltr',
    axes: dict.axes,
    mmUnit: dict.mmUnit,
    t(key, vars = {}) {
      const template = dict[key] ?? STRINGS.en[key] ?? key;
      return String(template).replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : ''));
    },
    term(text) {
      return translateTerm(text, code);
    }
  };
}
